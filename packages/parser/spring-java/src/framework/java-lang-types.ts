export function qualifyJavaLangType(typeName: string): string {
  const separator = typeName.indexOf(".");
  const topLevelName = separator < 0 ? typeName : typeName.slice(0, separator);
  return JAVA_LANG_TYPE_NAMES.has(topLevelName)
    ? "java.lang." + typeName
    : typeName;
}
